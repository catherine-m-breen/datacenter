import os
import glob
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import matplotlib.lines as mlines
from matplotlib.backends.backend_pdf import PdfPages
import warnings

warnings.filterwarnings('ignore')

# ==========================================
# CONFIGURATION
# ==========================================
PROCESS_ALL_STATIONS = False  # Set to False to only plot VA & TX stations

STATION_DIR = '/discover/nobackup/cmbreen/datacenters/uscrn_independent_data'
QAQC_DIR = './station_qaqc_reports'
OUTPUT_PDF = 'missing_data_timeline_with_2008_2010.pdf'

# Dynamically gather station files based on toggle
if PROCESS_ALL_STATIONS:
    station_files = sorted([f for f in glob.glob(os.path.join(STATION_DIR, '*.csv')) 
                            if not os.path.basename(f).startswith('all_')])
else:
    station_files = sorted(glob.glob(os.path.join(STATION_DIR, 'VA_*.csv')) + \
                           glob.glob(os.path.join(STATION_DIR, 'TX_*.csv')))

print(f"Found {len(station_files)} total stations to plot.")
print(f"Generating timeline plots: {OUTPUT_PDF}")

# Dynamically size the figure height based on the number of stations
fig_height = max(6, len(station_files) * 0.4)

# Create figures and axes for our 4 timeline plots
fig_main, ax_main = plt.subplots(figsize=(16, fig_height))
fig_08, ax_08 = plt.subplots(figsize=(16, fig_height))
fig_09, ax_09 = plt.subplots(figsize=(16, fig_height))
fig_10, ax_10 = plt.subplots(figsize=(16, fig_height))

zoom_axes = {2008: ax_08, 2009: ax_09, 2010: ax_10}

station_names = []
y_ticks = []
heatmap_data = [] # To store missing % for the heatmap

for idx, stn_file in enumerate(station_files):
    stn_name = os.path.basename(stn_file).replace('.csv', '')
    station_names.append(stn_name)
    y_ticks.append(idx)
    
    # 1. Get the operational lifespan from the original file
    df_orig = pd.read_csv(stn_file, usecols=['datetime'])
    df_orig['datetime'] = pd.to_datetime(df_orig['datetime'], errors='coerce', utc=True).dt.tz_localize(None)
    start_date = df_orig['datetime'].min()
    end_date = df_orig['datetime'].max()
    
    # Plot main grey line
    ax_main.plot([start_date, end_date], [idx, idx], color='lightgrey', linewidth=4, zorder=1)
    
    # Plot grey lines on zoom axes
    for yr, ax_yr in zoom_axes.items():
        ax_yr.plot([start_date, end_date], [idx, idx], color='lightgrey', linewidth=4, zorder=1)
    
    # 2. Look for the missing timestamps file generated by the QAQC script
    missing_file = os.path.join(QAQC_DIR, f"{stn_name}_missing_timestamps.csv")
    df_miss = pd.DataFrame()
    
    if os.path.exists(missing_file):
        df_miss = pd.read_csv(missing_file, usecols=['datetime'])
        if not df_miss.empty:
            df_miss['datetime'] = pd.to_datetime(df_miss['datetime'], errors='coerce', utc=True).dt.tz_localize(None)
            
            # Plot on main axis
            ax_main.plot(df_miss['datetime'], [idx] * len(df_miss), 
                         marker='|', color='red', markersize=12, linestyle='None', zorder=2)
            
            # Plot on zoom axes (filtering to the specific year for cleaner rendering)
            for yr, ax_yr in zoom_axes.items():
                df_miss_yr = df_miss[df_miss['datetime'].dt.year == yr]
                if not df_miss_yr.empty:
                    ax_yr.plot(df_miss_yr['datetime'], [idx] * len(df_miss_yr), 
                               marker='|', color='red', markersize=12, linestyle='None', zorder=2)
    else:
        print(f" -> [WARNING] No QAQC file found for {stn_name}. Missing data will not be plotted.")
    
    # 3. Calculate heatmap statistics for 2008, 2009, 2010
    heat_record = {'Station': stn_name}
    for yr in [2008, 2009, 2010]:
        yr_start = pd.Timestamp(f'{yr}-01-01')
        yr_end = pd.Timestamp(f'{yr}-12-31 23:59:59')
        
        # Determine how long the station was ACTUALLY operating during this specific year
        op_start = max(start_date, yr_start)
        op_end = min(end_date, yr_end)
        
        if op_start < op_end:
            # Calculate total operating hours in this year
            expected_hours = (op_end - op_start).total_seconds() / 3600.0
            
            if expected_hours > 0:
                if not df_miss.empty:
                    # Count missing hours in this year
                    miss_yr = df_miss[(df_miss['datetime'] >= yr_start) & (df_miss['datetime'] <= yr_end)]
                    miss_count = len(miss_yr['datetime'].drop_duplicates())
                else:
                    miss_count = 0
                
                # Calculate percentage
                pct_missing = (miss_count / expected_hours) * 100.0
            else:
                pct_missing = np.nan
        else:
            # Station was not operating at all during this year
            pct_missing = np.nan
            
        heat_record[str(yr)] = pct_missing
        
    heatmap_data.append(heat_record)

# ==========================================
# AESTHETICS & FORMATTING: TIMELINE PLOTS
# ==========================================
def format_axis(ax, title, is_zoom=False, year=None):
    ax.set_yticks(y_ticks)
    ax.set_yticklabels(station_names, fontsize=10)
    ax.set_title(title, fontsize=18, fontweight='bold', pad=20)
    ax.set_xlabel("Time", fontsize=12, fontweight='bold')
    
    if is_zoom and year:
        ax.set_xlim(pd.Timestamp(f'{year}-01-01'), pd.Timestamp(f'{year}-12-31'))
        ax.xaxis.set_major_locator(mdates.MonthLocator())
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%b'))  # Jan, Feb, Mar...
    else:
        ax.set_xlim(pd.Timestamp('2002-01-01'), pd.Timestamp('2026-12-31'))
        ax.xaxis.set_major_locator(mdates.YearLocator())
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y'))
    
    # Rotate X labels and format grid
    plt.setp(ax.get_xticklabels(), rotation=45, ha='right')
    
    # Legend
    grey_line = mlines.Line2D([], [], color='lightgrey', linewidth=4, label='Station Operating')
    red_tick = mlines.Line2D([], [], color='red', marker='|', linestyle='None', markersize=12, label='Missing Hourly Data')
    ax.legend(handles=[grey_line, red_tick], loc='upper right', bbox_to_anchor=(1.0, 1.05), framealpha=1.0)
    
    ax.grid(axis='x', linestyle='--', alpha=0.6)
    ax.set_axisbelow(True)

format_axis(ax_main, "Missing Data Timeline (2002 - 2026)")
format_axis(ax_08, "Missing Data Timeline - 2008", is_zoom=True, year=2008)
format_axis(ax_09, "Missing Data Timeline - 2009", is_zoom=True, year=2009)
format_axis(ax_10, "Missing Data Timeline - 2010", is_zoom=True, year=2010)

# ==========================================
# GENERATE HEATMAP (2008 - 2010)
# ==========================================
df_heat = pd.DataFrame(heatmap_data).set_index('Station')
fig_heat, ax_heat = plt.subplots(figsize=(8, fig_height))

# Mask NaNs (stations that weren't operating during that year)
data = df_heat.values
data_masked = np.ma.masked_invalid(data)

# Setup color map (Grey for N/A, Reds for data)
cmap = plt.cm.Reds
cmap.set_bad(color='lightgrey')

cax = ax_heat.imshow(data_masked, cmap=cmap, aspect='auto')
cbar = fig_heat.colorbar(cax, ax=ax_heat)
cbar.set_label('% Missing Data (of Expected Operating Hours)', rotation=270, labelpad=15)

# Formatting Heatmap
ax_heat.set_yticks(range(len(df_heat.index)))
ax_heat.set_yticklabels(df_heat.index, fontsize=10)
ax_heat.set_xticks(range(len(df_heat.columns)))
ax_heat.set_xticklabels(df_heat.columns, fontsize=12)
ax_heat.set_title("Missing Data Percentage (2008 - 2010)", fontsize=18, fontweight='bold', pad=20)

# Annotate heatmap with the actual percentage numbers
for i in range(len(df_heat.index)):
    for j in range(len(df_heat.columns)):
        val = data[i, j]
        if not np.isnan(val):
            # Show small percentages clearly, e.g. 0.05%
            text = f"{val:.2f}%" 
            # Switch text color to white if the cell background is dark red
            color = "white" if val > (np.nanmax(data) / 2) else "black"
            ax_heat.text(j, i, text, ha="center", va="center", color=color, fontsize=9)
        else:
            ax_heat.text(j, i, "N/A", ha="center", va="center", color="black", fontsize=9)

# ==========================================
# SAVE TO MULTIPAGE PDF
# ==========================================
fig_main.tight_layout()
fig_08.tight_layout()
fig_09.tight_layout()
fig_10.tight_layout()
fig_heat.tight_layout()

with PdfPages(OUTPUT_PDF) as pdf:
    pdf.savefig(fig_main)
    pdf.savefig(fig_08)
    pdf.savefig(fig_09)
    pdf.savefig(fig_10)
    pdf.savefig(fig_heat)

# Close all figures to free memory
plt.close('all')

print(f"Done! Saved 5 pages to {OUTPUT_PDF}.")